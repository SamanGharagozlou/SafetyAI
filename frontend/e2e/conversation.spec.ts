import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { mockMedia } from './media'
import { detectSpeechTurn } from './textFallback'

async function join(page: Page) {
  await page.goto('/join')
  await page.getByLabel('What should I call you?').fill('Nova')
  await page.getByRole('button', { name: "Let's Get Started" }).click()
}
for (const viewport of [{ width: 320, height: 568 }, { width: 375, height: 667 }, { width: 390, height: 844 }, { width: 430, height: 932 }, { width: 667, height: 375 }]) {
  test(`complete automatic call at ${viewport.width}×${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    await mockMedia(page)
    await page.clock.install()
    const unexpected: string[] = [], errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.method() !== 'GET' || !request.url().startsWith('http://127.0.0.1:4173/')) unexpected.push(request.url()) })
    const screen = page.locator('.call-screen')
    const screenshot = async (name: string) => {
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if(name !== 'pre-call' && name !== 'ended-call') await expect(page.getByRole('button', {name:'End Call'})).toBeInViewport()
      await page.clock.runFor(100)
      await page.screenshot({ path: testInfo.outputPath(`${name}.png`), animations: 'disabled' })
    }
    await join(page)
    await expect(page.getByRole('button', { name: 'Start Conversation' })).toBeVisible()
    await expect(page.getByRole('button', { name: /^(Mute|Unmute|End Call|Type a request)$/ })).toHaveCount(0)
    expect(await page.evaluate(() => window.__voiceTest.requests)).toBe(0)
    await screenshot('pre-call')
    await page.getByRole('button', { name: 'Start Conversation' }).click()
    await page.clock.runFor(650)
    await expect(screen).toHaveAttribute('data-call-state', 'listening')
    await expect(page.getByRole('group', { name: 'Call controls' }).getByRole('button')).toHaveCount(2)
    await expect(page.getByRole('button', { name: 'End Call' })).toBeInViewport()
    await expect(page.getByRole('button', { name: /^(Continue|Stop Recording|Done speaking)$/ })).toHaveCount(0)
    await expect(page.locator('audio')).toHaveCount(0)
    await screenshot('active-listening')
    await page.getByRole('button', { name: 'Mute', exact: true }).click()
    await expect(screen).toHaveAttribute('data-call-state', 'muted')
    expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
    await screenshot('muted')
    await page.getByRole('button', { name: 'Unmute' }).click()
    await detectSpeechTurn(page)
    await expect(screen).toHaveAttribute('data-call-state', 'awaiting_review')
    await expect(page.getByRole('heading', { name: 'Speech recognition unavailable' })).toBeVisible()
    expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
    await screenshot('transcript-unavailable')
    await page.getByLabel('Your request', { exact: true }).fill('Hello')
    await page.getByRole('button', { name: 'Review request' }).click()
    await expect(page.getByRole('heading', { name: 'Confirm your request' })).toBeFocused()
    await screenshot('confirmation')
    await page.getByRole('button', { name: 'Confirm demo request' }).dblclick()
    await page.clock.runFor(4500)
    await expect(screen).toHaveAttribute('data-call-state', 'responding')
    await expect(page.locator('.history-user')).toHaveCount(1)
    await expect(page.getByText('ClawMetry · Demo text response')).toBeVisible()
    await screenshot('demo-response')
    await page.clock.runFor(2500)
    await expect(screen).toHaveAttribute('data-call-state', 'listening')
    await detectSpeechTurn(page)
    await page.getByLabel('Your request', { exact: true }).fill('Help')
    await page.getByRole('button', { name: 'Review request' }).click()
    await page.getByRole('button', { name: 'Confirm demo request' }).click()
    await page.clock.runFor(4500)
    await expect(page.getByText('Earlier turns (1)')).toBeVisible()
    await page.getByRole('button', { name: 'End Call' }).click()
    await expect(page.getByRole('button', { name: 'Start Conversation' })).toBeFocused()
    await expect(page.locator('.call-history')).toHaveCount(0)
    expect(await page.evaluate(() => ({ active: window.__voiceTest.activeTracks, open: window.__voiceTest.contexts - window.__voiceTest.closedContexts }))).toEqual({ active: 0, open: 0 })
    await screenshot('ended-call')
    expect(unexpected).toEqual([]); expect(errors).toEqual([])
  })
}

test('End during native permission releases a late grant', async ({ page }) => {
  await mockMedia(page, 'pending'); await join(page)
  await page.getByRole('button', { name: 'Start Conversation' }).click()
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state', 'requesting_permission')
  await page.getByRole('button', { name: 'End Call' }).click()
  await page.evaluate(() => window.__voiceTest.resolve?.())
  await expect(page.getByRole('button', { name: 'Start Conversation' })).toBeEnabled()
  expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
})

test('Mute during native permission requires explicit Unmute after late grant', async ({ page }) => {
  await mockMedia(page, 'pending'); await join(page)
  await page.getByRole('button', { name: 'Start Conversation' }).click()
  await page.getByRole('button', { name: 'Mute', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Unmute' })).toBeDisabled()
  await page.evaluate(() => window.__voiceTest.resolve?.())
  await expect(page.getByRole('button', { name: 'Unmute' })).toBeEnabled()
  expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
})

for (const interruption of ['tab', 'context', 'device']) {
  test(`releases capture on ${interruption} interruption`, async ({ page }) => {
    await mockMedia(page); await join(page)
    await page.getByRole('button', { name: 'Start Conversation' }).click()
    await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state', 'listening')
    await page.evaluate(kind => {
      if (kind === 'context') window.__voiceTest.interrupt()
      else if (kind === 'device') window.__voiceTest.remove()
      else { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' }); document.dispatchEvent(new Event('visibilitychange')) }
    }, interruption)
    expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
    await expect(page.getByText('Microphone off', { exact: true })).toBeVisible()
    await expect(page.locator('.call-screen')).not.toHaveAttribute('data-call-state', 'listening')
  })
}

test('silent buffers roll without empty turns; speech caps at 20 seconds, call survives until expiry', async ({ page }) => {
  await mockMedia(page); await page.clock.install(); await join(page)
  await page.getByRole('button', { name: 'Start Conversation' }).click()
  await page.clock.runFor(40_500)
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state', 'listening')
  await expect(page.getByLabel('Your request', {exact:true})).toHaveCount(0)
  expect(await page.evaluate(() => window.__voiceTest.revoked)).toBe(0)
  await page.evaluate(() => { window.__voiceTest.rms = .1 })
  await page.clock.runFor(20_500)
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state', 'awaiting_review')
  await expect(page.getByRole('button', { name: 'End Call' })).toBeVisible()
  expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
  await page.clock.fastForward(600_000)
  await expect(page.getByRole('status')).toContainText('has expired')
  await expect(page.getByRole('button', { name: 'End Call' })).toHaveCount(0)
})


test('visualizer uses measured audio and reduced motion suppresses movement without disabling VAD', async ({page}) => {
  await mockMedia(page); await page.clock.install(); await page.emulateMedia({reducedMotion:'no-preference'}); await join(page)
  await expect(page.locator('.call-waveform')).toHaveAttribute('data-reactive','false')
  await page.getByRole('button',{name:'Start Conversation'}).click()
  await page.clock.runFor(650)
  await expect(page.locator('.call-waveform')).toHaveAttribute('data-reactive','true')
  const quiet = Number(await page.locator('.orb-ring').getAttribute('r'))
  await page.evaluate(() => {window.__voiceTest.rms=.1})
  await page.clock.runFor(350)
  expect(Number(await page.locator('.orb-ring').getAttribute('r'))).toBeGreaterThan(quiet)
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(page.locator('.call-waveform')).toHaveAttribute('data-reactive','false')
  await expect(page.locator('.orb-ring')).toHaveAttribute('r','112')
  await expect(page.locator('.robot')).toHaveCSS('animation-name','none')
  await page.evaluate(() => {window.__voiceTest.rms=.002})
  await page.clock.runFor(1300)
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state','awaiting_review')
})

test('manual Finish and Mute discard speech without leaving the active call', async ({page}) => {
  await mockMedia(page); await page.clock.install(); await join(page)
  await page.getByRole('button',{name:'Start Conversation'}).click()
  await page.clock.runFor(650)
  await page.evaluate(() => {window.__voiceTest.rms=.1})
  await page.clock.runFor(350)
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state','speech_detected')
  await page.getByRole('button',{name:'Mute',exact:true}).click()
  expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
  await expect(page.getByLabel('Your request',{exact:true})).toHaveCount(0)
  await page.evaluate(() => {window.__voiceTest.rms=.002})
  await page.getByRole('button',{name:'Unmute'}).click()
  await page.clock.runFor(650)
  await page.evaluate(() => {window.__voiceTest.rms=.1})
  await page.clock.runFor(350)
  await page.getByRole('button',{name:'Finish turn'}).click()
  await expect(page.locator('.call-screen')).toHaveAttribute('data-call-state','awaiting_review')
  await expect(page.getByRole('button',{name:'End Call'})).toBeVisible()
  expect(await page.evaluate(() => window.__voiceTest.activeTracks)).toBe(0)
})

