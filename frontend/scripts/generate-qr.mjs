import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import encodeQR from 'qr'

export function validateTarget(target, allowLocal = false) {
  if (!target) throw new Error('An explicit target URL is required; no URL is generated by default.')
  let url
  try { url = new URL(target) } catch { throw new Error('Target must be an absolute URL.') }
  if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password) {
    throw new Error('Use an HTTP(S) URL without credentials.')
  }
  if (url.pathname !== '/join' || url.search || url.hash) {
    throw new Error('Use the exact /join path without query parameters or a fragment.')
  }
  const host = url.hostname.toLowerCase().replace(/\.$/, '')
  const local = host === 'localhost' || host.endsWith('.localhost') || host.endsWith('.local') || host === '[::1]' || host === '0.0.0.0' || /^127\./.test(host) || /^10\./.test(host) || /^192\.168\./.test(host) || /^172\.(1[6-9]|2\d|3[01])\./.test(host) || /^\[(?:f[cd]|fe[89ab])/.test(host)
  if ((local || url.protocol !== 'https:') && !allowLocal) {
    throw new Error('Final QR codes require HTTPS and a non-local target. For an intentional development URL, pass --allow-local explicitly.')
  }
  return url.href
}

export async function generateQR(args) {
  const allowLocal = args.includes('--allow-local')
  const positional = args.filter(arg => arg !== '--allow-local')
  if (positional.length !== 2 || positional.some(arg => arg.startsWith('--'))) {
    throw new Error('Usage: npm run qr -- <explicit-target-URL>/join <output.svg> [--allow-local]')
  }
  const [target, output] = positional
  const url = validateTarget(target, allowLocal)
  if (!output.toLowerCase().endsWith('.svg')) throw new Error('Output filename must end in .svg.')
  const svg = encodeQR(url, 'svg', { ecc: 'quartile', border: 4, scale: 12 })
  // Do not silently overwrite an existing printable asset.
  await writeFile(output, svg, { flag: 'wx' })
  return { url, output: resolve(output) }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const result = await generateQR(process.argv.slice(2))
    console.log(`QR target: ${result.url}\nPrintable SVG: ${result.output}`)
    if (process.argv.includes('--allow-local')) console.log('Development override used. Verify that this URL is reachable from the scanning phone.')
  } catch (error) {
    console.error(`QR generation failed: ${error.message}`)
    process.exitCode = 1
  }
}
